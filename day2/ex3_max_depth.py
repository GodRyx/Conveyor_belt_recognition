# -*- coding: utf-8 -*-
"""
练习3-A：求列表的最大嵌套深度
------------------------------
题目要求：
    写一个函数，传入的参数是一个列表（元素可能也是列表），
    返回这个列表最大的嵌套深度。
    例如：
        [1, 2, 3]       的深度是 1（最外层算第 1 层，没有套娃）
        [[1], [2,[3]]]  的深度是 3（[3] 套在 [2,[3]] 里，再套在最外层）

方法：递归（recursion）
    核心思想：一个列表的深度 = 1（自己这层） + 它所有子列表里"最深的那个"的深度。
    类比 Java：一个方法在方法体里调用它自己，就是递归。
    递归必须有两个东西：
        1. 终止条件（不递归就返回）—— 这里是"列表为空，深度就是 1"
        2. 递归调用（缩小范围自己调用自己）—— 这里是"对每个子元素算深度"
"""

def max_depth(lst):
    """
    返回列表 lst 的最大嵌套深度。
    lst 一定是个列表（调用方保证），但里面的元素可能是列表也可能是普通数字。
    """
    # 如果列表是空的，比如 [], 深度就是 1（本身占一层）
    if not lst:                       # not lst 表示"列表为空"
        return 1

    max_sub = 0                       # 记录"子元素里最深的深度"，先假设没有子列表

    for item in lst:                  # 遍历每个元素
        if isinstance(item, list):    # 如果这个元素本身是列表 → 它还有深度，递归下去
            d = max_depth(item)       # 递归：算出这个子列表的深度
            if d > max_sub:           # 挑出所有子列表里最深的那个
                max_sub = d

    # 自己这层 +1。max_sub 存的是"子列表最深的深度"，没子列表时 max_sub=0，结果就是 1。
    return max_sub + 1


if __name__ == "__main__":
    # 下面几个例子可以运行测试（真正的测试请看 ex3_test.py，那里用 unittest）
    print("[1, 2, 3]          的深度 =", max_depth([1, 2, 3]))            # 期望 1
    print("[[1], [2,[3]]]     的深度 =", max_depth([[1], [2, [3]]]))      # 期望 3
    print("[]                 的深度 =", max_depth([]))                   # 期望 1
    print("[[1]]              的深度 =", max_depth([[1]]))                # 期望 2
    print("[[[[]]]]           的深度 =", max_depth([[[[]]]]))             # 期望 4
