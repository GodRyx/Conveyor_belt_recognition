# -*- coding: utf-8 -*-
"""
练习2-B：十进制转二进制 / 十六进制（不许用内置函数）
--------------------------------------------------
题目要求：
    输入一个十进制整数，输出它的二进制和十六进制。
    禁止使用 Python 内置的 bin() 和 hex()，要自己写转换过程。

核心方法（答辩必讲）—— "除 N 取余，倒序排列"：
    以十进制 13 转二进制为例：
        13 ÷ 2 = 6 余 1   ← 余数从下往上读
        6  ÷ 2 = 3 余 0
        3  ÷ 2 = 1 余 1
        1  ÷ 2 = 0 余 1
        从下往上读余数：1101  →  13 的二进制就是 1101  ✅

    十六进制多一步：余数 10~15 要用字母 A~F 表示（因为一位最大只到 15）。
"""

# ---------- 1. 十进制转二进制（除 2 取余，倒序） ----------
def to_binary(n):
    """
    把十进制整数 n 转成二进制字符串。
    思路：一直除以 2，把余数存下来，最后把余数反过来拼。
    """
    if n == 0:                       # 特殊情况：0 的二进制就是 "0"
        return "0"

    remainders = []                  # 用来存每一步的余数（注意顺序是反的）
    while n > 0:                     # 除到 n 变成 0 为止
        r = n % 2                    # 取余数（0 或 1）
        remainders.append(r)         # 放到列表里
        n = n // 2                   # 整除 2，得到下一步要除的数（// 是整除）

    # 现在 remainders 里是[最低位, ..., 最高位]，正好是反的
    # 把它反转成字符串拼起来。str(x) 把数字转成字符串，join 把字符连起来。
    remainders.reverse()             # 倒序
    return "".join(str(x) for x in remainders)   # 列表推导式：把每个数字变字符再拼接


# ---------- 2. 十进制转十六进制（除 16 取余，倒序，余数 10~15 用 A~F） ----------
def to_hex(n):
    """
    把十进制整数 n 转成十六进制字符串。
    和二进制同理，只是除以 16，且余数 10~15 要换成 A~F。
    """
    digits = "0123456789ABCDEF"      # 十六进制用到的 16 个字符，下标 0~15

    if n == 0:
        return "0"

    remainders = []
    while n > 0:
        r = n % 16                   # 取余数（0~15）
        remainders.append(digits[r]) # 直接用余数当下标，取对应字符（A~F 自动搞定）
        n = n // 16                  # 整除 16

    remainders.reverse()
    return "".join(remainders)       # 这里已经是字符串，不用再 str()


# ---------- 3. 主程序入口 ----------
if __name__ == "__main__":
    # input() 拿到的是"字符串"，int() 转成整数。负数/非数字会报错，这里先不管。
    num = int(input("请输入一个十进制整数："))

    binary = to_binary(num)
    hex_str = to_hex(num)

    print(f"{num} 的二进制是：{binary}")
    print(f"{num} 的十六进制是：{hex_str}")

    # ---- 下面这行用来"自检"：用内置函数对比，看手写的对不对（答辩演示超有用）----
    print(f"（验证：bin() 得 {bin(num)}，hex() 得 {hex(num)}，结果一致就说明写对了）")
